const dictionaries: Record<Language, Record<string, string>> = {
  es: {},
  en,
};

export function translate(language: Language, text: string): string {
  if (language === "es") return text;
  return dictionaries[language][text] ?? text;
}

export const STORAGE_KEYS = {
  language: "vyntra.pref.language",
  theme: "vyntra.pref.theme",
} as const;

/**
 * Se inyecta antes de pintar para que el tema y el idioma guardados se
 * apliquen sin parpadeo y sin desajuste de hidratación.
 */
export const PREFERENCES_BOOT_SCRIPT = `
(function(){
  try {
    var t = localStorage.getItem('${STORAGE_KEYS.theme}');
    if (t !== 'dark' && t !== 'light') {
      t = window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light';
    }
    document.documentElement.setAttribute('data-theme', t);
    var l = localStorage.getItem('${STORAGE_KEYS.language}');
    if (l !== 'en' && l !== 'es') l = 'es';
    document.documentElement.setAttribute('lang', l);
  } catch (e) {}
})();
`;
